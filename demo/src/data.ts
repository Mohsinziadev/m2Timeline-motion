/** A brand-new event used by the playground's "Add event" button. */
export function makeExtraEvent(n: number): TimelineEvent {
  return {
    id: `new-${n}`,
    title: `New event #${n}`,
    date: d(n * 3),
    icon: '✨',
    status: 'upcoming',
    category: 'New',
    description: 'Added at runtime — the timeline animates it in.',
  };
}
