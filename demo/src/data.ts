const DAY = 864e5;
/**
 * The day the demo was built (injected by Vite as `__DEMO_DAY__`). Relative sample dates are anchored
 * to it rather than to `Date.now()`, so the prerendered page and the hydrating client produce
 * identical markup, while roadmap / project / feed data still looks current.
 */
const today = new Date(`${__DEMO_DAY__}T00:00:00Z`);
/** ISO date `offset` days from the build day. */
const d = (offset: number) => new Date(today.getTime() + offset * DAY).toISOString().slice(0, 10);
/** ISO timestamp `hours` before noon (UTC) on the build day. */
const ago = (hours: number) => new Date(today.getTime() + 12 * 36e5 - hours * 36e5).toISOString().replace('.000', '');

